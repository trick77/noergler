func TestRefuseRepoTarget(t *testing.T) {
	ctx := context.Background()
	repoTarget := Target{Project: "PROJ", Repo: "my-repo"}

	// A project target is never refused.
	if got, err := newOnboarder(t, newTeam(whole("PROJ")), &fakeAdmin{}, botReading(), Options{}).
		refuseRepoTarget(ctx, Target{Project: "PROJ"}, Claim{Kind: "whole"}); got != "" || err != nil {
		t.Errorf("project target refused: %q %v", got, err)
	}

	// A repo under a whole-project claim is refused without asking Bitbucket.
	got, err := newOnboarder(t, newTeam(whole("PROJ")), &fakeAdmin{}, botReading(), Options{}).
		refuseRepoTarget(ctx, repoTarget, Claim{Kind: "whole"})
	if err != nil || got != wholeClaimReason(repoTarget) {
		t.Errorf("whole claim: %q %v", got, err)
	}

	// Our project hook next to the repo target: refused, naming its id.
	admin := &fakeAdmin{hooks: map[string][]map[string]any{"PROJ": {goodHook(map[string]any{"id": float64(5)})}}}
	got, err = newOnboarder(t, newTeam(repos("PROJ", "my-repo")), admin, botReading(), Options{}).
		refuseRepoTarget(ctx, repoTarget, Claim{Kind: "repos"})
	want := "PROJ still has this instance's project webhook (id=5), which delivers every event as well; remove it first"
	if err != nil || got != want {
		t.Errorf("project hook present:\n%q\nwant\n%q (err %v)", got, want, err)
	}

	// A foreign project hook is not ours and does not block.
	admin = &fakeAdmin{hooks: map[string][]map[string]any{
		"PROJ": {goodHook(map[string]any{"url": "https://old.test/webhook/p"})}}}
	if got, err := newOnboarder(t, newTeam(repos("PROJ", "my-repo")), admin, botReading(), Options{}).
		refuseRepoTarget(ctx, repoTarget, Claim{Kind: "repos"}); got != "" || err != nil {
		t.Errorf("foreign project hook blocked: %q %v", got, err)
	}

	// 401/403 on the guard: no project admin, nothing more to check.
	for _, code := range []int{401, 403} {
		admin = &fakeAdmin{hookErr: map[string]error{"PROJ": statusErr(code, "nope")}}
		if got, err := newOnboarder(t, newTeam(repos("PROJ", "my-repo")), admin, botReading(), Options{}).
			refuseRepoTarget(ctx, repoTarget, Claim{Kind: "repos"}); got != "" || err != nil {
			t.Errorf("HTTP %d: %q %v", code, got, err)
		}
	}

	// Any other failure is an error: a hiccup is not a licence to double-hook.
	for _, e := range []error{statusErr(404, "x"), statusErr(503, "x"), transportErr("dial tcp: timeout")} {
		admin = &fakeAdmin{hookErr: map[string]error{"PROJ": e}}
		if _, err := newOnboarder(t, newTeam(repos("PROJ", "my-repo")), admin, botReading(), Options{}).
			refuseRepoTarget(ctx, repoTarget, Claim{Kind: "repos"}); err == nil {
			t.Errorf("%v was swallowed", e)
		}
	}
}

func TestTruncateRunesCountsCharacters(t *testing.T) {
	// 300 two-byte runes: Python's [:200] keeps 200 of them, not 200 bytes.
	s := strings.Repeat("ä", 300)
	if got := truncateRunes(s, 200); len([]rune(got)) != 200 {
		t.Errorf("kept %d runes, want 200", len([]rune(got)))
	}
	if got := truncateRunes("short", 200); got != "short" {
		t.Errorf("truncated a short string: %q", got)
	}
}

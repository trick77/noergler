func strayAdmin() *fakeAdmin {
	return &fakeAdmin{
		repos: map[string][]map[string]any{"PROJ": {
			{"slug": "my-repo"},
			{"slug": float64(1)}, // dropped: not a string
			{"name": "no-slug"},  // dropped: absent
			{"slug": "other"},
			{"slug": "clean"},
		}},
		hooks: map[string][]map[string]any{
			"PROJ/my-repo": {goodHook(map[string]any{"id": float64(8)})},
			"PROJ/other":   {goodHook(map[string]any{"id": float64(9), "url": "https://old.test/webhook/p"})},
			"PROJ/clean":   {{"name": "something-else", "url": webhookURL + "/x"}},
		},
	}
}


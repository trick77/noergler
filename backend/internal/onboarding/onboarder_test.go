// Results are indexed back into listing order, whatever order they finish in.
func TestStrayRepoHooksKeepsListingOrderUnderConcurrency(t *testing.T) {
	admin := strayAdmin()
	slugs := []string{"a", "b", "c", "d", "e", "f", "g", "h"}
	admin.repos["BIG"] = nil
	admin.hooks = map[string][]map[string]any{}
	for i, s := range slugs {
		admin.repos["BIG"] = append(admin.repos["BIG"], map[string]any{"slug": s})
		admin.hooks["BIG/"+s] = []map[string]any{goodHook(map[string]any{"id": float64(100 + i)})}
	}
	// Later slugs answer first.
	admin.onList = func(_, repo string) {
		for i, s := range slugs {
			if s == repo {
				time.Sleep(time.Duration(len(slugs)-i) * 2 * time.Millisecond)
				return
			}
		}
	}
	stray, _, err := newOnboarder(t, newTeam(whole("BIG")), admin, botReading(), Options{}).
		StrayRepoHooks(context.Background(), "BIG")
	if err != nil {
		t.Fatalf("StrayRepoHooks: %v", err)
	}
	if len(stray) != len(slugs) {
		t.Fatalf("got %d stray hooks, want %d", len(stray), len(slugs))
	}
	for i, s := range slugs {
		if stray[i].Target.Repo != s || stray[i].ID != 100+i {
			t.Errorf("stray[%d] = %+v, want %s#%d", i, stray[i], s, 100+i)
		}
	}
	if max := admin.maxInFlight.Load(); max > repoHookConcurrency || max < 2 {
		t.Errorf("max listings in flight = %d, want 2..%d", max, repoHookConcurrency)
	}
}

// The first error in listing order wins and propagates.
func TestStrayRepoHooksPropagatesTheFirstError(t *testing.T) {
	admin := strayAdmin()
	admin.hookErr = map[string]error{
		"PROJ/other": statusErr(500, "boom"),
		"PROJ/clean": statusErr(503, "later"),
	}
	if _, _, err := newOnboarder(t, newTeam(whole("PROJ")), admin, botReading(), Options{}).
		StrayRepoHooks(context.Background(), "PROJ"); err == nil || !strings.Contains(err.Error(), "500") {
		t.Errorf("err = %v, want the 500", err)
	}
	// A failed repo listing propagates too.
	admin = strayAdmin()
	admin.reposErr = map[string]error{"PROJ": statusErr(403, "no")}
	if _, _, err := newOnboarder(t, newTeam(whole("PROJ")), admin, botReading(), Options{}).
		StrayRepoHooks(context.Background(), "PROJ"); err == nil {
		t.Error("a failed repo listing was swallowed")
	}
}

// Pruning deletes ours one at a time and never touches the foreign one.
func TestPruneRepoHooksDeletesSequentiallyAndLeavesForeign(t *testing.T) {
	admin := strayAdmin()
	var mu sync.Mutex
	concurrent := false
	busy := false
	admin.deleteFn = func(_, _ string, _ int) error {
		mu.Lock()
		if busy {
			concurrent = true
		}
		busy = true
		mu.Unlock()
		time.Sleep(time.Millisecond)
		mu.Lock()
		busy = false
		mu.Unlock()
		return nil
	}
	pruned, err := newOnboarder(t, newTeam(whole("PROJ")), admin, botReading(), Options{}).
		PruneRepoHooks(context.Background(), "PROJ")
	if err != nil {
		t.Fatalf("PruneRepoHooks: %v", err)
	}
	if strings.Join(pruned, ",") != "PROJ/my-repo" {
		t.Errorf("pruned = %v", pruned)
	}
	if strings.Join(admin.deleted, ",") != "PROJ/my-repo#8" {
		t.Errorf("deleted = %v, want only our stray hook", admin.deleted)
	}
	if concurrent {
		t.Error("deletions overlapped; they must be sequential")
	}
}


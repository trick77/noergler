// diffTooLargeSummaryEN is the skip summary when the PR diff exceeds the byte
// cap. limit is in bytes.
func diffTooLargeSummaryEN(limit int) string {
	return WrapProse("### Review skipped — diff too large 🛑\n\n" +
		fmt.Sprintf("The PR diff exceeds %d MiB, more than fits in one ", limit/(1024*1024)) +
		"review even after compression, so the review was not run.\n\n" +
		"**What to do**\n" +
		"- Split the change into smaller PRs, or move generated files, vendored " +
		"code and lockfile churn into their own PR.\n" +
		"- Push the smaller change and the next webhook event on this PR will " +
		"trigger a full review.\n")
}

// AgentsMDTooLargeSummary is the skip summary when the team's rules file
// (name) is over the hard token limit. customLink, when non-empty, is
// prepended to the further reading list, which is never wrapped: a break
// would land inside a link title, counted at the width of its hidden URL.
func AgentsMDTooLargeSummary(l lang.Lang, name string, tokens, limit int, customLink string) string {
	links := make([]Link, 0, len(agentsMDFurtherReading)+1)
	if cl, ok := ParseCustomLink(customLink); ok {
		links = append(links, cl)
	}
	links = append(links, agentsMDFurtherReading...)

	var fr strings.Builder
	for i, link := range links {
		if i > 0 {
			fr.WriteString("\n")
		}
		fmt.Fprintf(&fr, "- [%s](%s)", link.Title, link.URL)
	}
	if l == lang.EN {
		return agentsMDTooLargeSummaryEN(name, tokens, limit, fr.String())
	}
	return agentsMDTooLargeSummaryDE(name, tokens, limit, fr.String())
}

func agentsMDTooLargeSummaryEN(name string, tokens, limit int, fr string) string {
	return WrapProse(fmt.Sprintf("### Review skipped — `%s` too large 🛑\n\n", name)+
		fmt.Sprintf("`%s` weighs in at ~%s tokens, exceeding the configured ", name, Fmt(tokens))+
		fmt.Sprintf("hard limit of %s tokens. Oversized agent instructions crowd out ", Fmt(limit))+
		"the actual diff, degrade review quality (context rot), and inflate "+
		"inference cost, so the review was not run. "+
		fmt.Sprintf("The [ETH\u00a0study](%s) says the same: context files ", ETHStudyURL)+
		"*\"should only contain specific additional instructions beyond what is already "+
		"available in the codebase\"*.\n\n"+
		"**What to do**\n"+
		"- Keep what the code does not show: invariants, conventions, decisions and their why. "+
		"Cut what the code or the README already says; replace prose with terse rules.\n"+
		"- Move detailed reference material into separate files and link to "+
		"them; keep the main file lean.\n"+
		"- Push the slimmer file and the next webhook event on this PR will "+
		"trigger a full review.\n\n"+
		"**Configure**\n"+
		"- Raise the limit via `REVIEW_AGENTS_MD_MAX_TOKENS` on the noergler "+
		"service, or set it to `0` to disable the hard cut-off entirely "+
		"(the soft warning via `REVIEW_AGENTS_MD_WARN_TOKENS` remains).\n\n"+
		"**Further reading**\n") +
		fr + "\n"
}
